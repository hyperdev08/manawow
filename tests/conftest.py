"""Shared test cleanup and CI data guards."""
from __future__ import annotations

import sqlite3
from pathlib import Path

import pytest

from src.common import sqlite_tuning
from src.world import databases

ROOT = Path(__file__).resolve().parent.parent
WORLD_DB = ROOT / "data" / "world.db"

# The generated world database is deliberately not tracked.  Tests that read
# spells/creatures from it must skip in a clean checkout (including GitHub
# Actions) instead of failing before the server data has been imported.
_DATA_TESTS = (
    "test_aoe.py",
    "test_auras.py",
    "test_combat_systems.py",
)
_DATA_TEST_NAMES = {
    "test_protocol_selftest_passes",
    "test_real_northshire_loot_uses_known_items_and_gold",
}


def world_db_available() -> bool:
    """True when a populated generated world database is present."""
    try:
        if not WORLD_DB.is_file() or WORLD_DB.stat().st_size < 512_000:
            return False
        con = sqlite3.connect(f"file:{WORLD_DB}?mode=ro", uri=True)
        try:
            names = {
                row[0] for row in con.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table'")
            }
        finally:
            con.close()
    except (OSError, sqlite3.Error):
        return False
    return {"creature_templates", "spell_templates",
            "player_levelstats"} <= names


def pytest_collection_modifyitems(config, items):
    if world_db_available():
        return
    skip = pytest.mark.skip(
        reason="requires data/world.db generated by tools/import_wotlk_db.py")
    for item in items:
        filename = Path(str(item.fspath)).name
        if filename in _DATA_TESTS or item.name in _DATA_TEST_NAMES:
            item.add_marker(skip)


@pytest.fixture(autouse=True)
def _close_shared_read_connections():
    """Do not keep temp SQLite files open across tests on Windows."""
    yield
    sqlite_tuning.close_read_connections()
    databases.reset()
